// generated marks the index as written by make gen. It follows the H1,
// because markdownlint wants the H1 on the first line.
const generated = "<!-- Generated by make gen. Do not edit. -->"

// language holds the words of one index.
type language struct {
	ja         bool
	title      string
	intro      string // with %s for the link to ADR-0001
	columns    string
	none       string
	superseded string
	separator  string
}

var (
	indexEnglish = language{
		title: "Architecture decision records",
		intro: "Each record states one decision and the reason for it. " +
			"A later record replaces an earlier one by naming it in `supersedes`. " +
			"%s defines the format.",
		columns:    "| ID | Decision | Status | Date |",
		none:       "None yet.",
		superseded: "superseded by ",
		separator:  ", ",
	}
	indexJapanese = language{
		ja:    true,
		title: "アーキテクチャの決定の記録",
		intro: "記録1件には、決定を1つと、その理由を書く。" +
			"後の記録は、前の記録を `supersedes` に挙げて置き換える。" +
			"形式は %s が定める。",
		columns:    "| ID | 決定 | 状態 | 日付 |",
		none:       "まだない。",
		superseded: "次の記録が置き換えた：",
		separator:  "、",
	}
)

// index returns the English and the Japanese index of the records. The
// Japanese index ends with the i18n marker of the English one.
func (r *repo) index() (en, ja []byte) {
	fronts := map[*record]frontMatter{}
	supersededBy := map[string][]*record{}
	for _, rec := range r.records {
		if rec.en == nil {
			continue
		}
		fm, _ := readFront(rec.en)
		fronts[rec] = fm
		if fm.status == "accepted" {
			for _, id := range fm.supersedes {
				supersededBy[id] = append(supersededBy[id], rec)
			}
		}
	}
	en = r.render(indexEnglish, fronts, supersededBy)
	ja = r.render(indexJapanese, fronts, supersededBy)
	marker := i18n.Marker(path.Base(indexEN), en)
	return en, append(ja, []byte("\n"+marker+"\n")...)
}

// render writes the index in one language.
func (r *repo) render(lang language, fronts map[*record]frontMatter, supersededBy map[string][]*record) []byte {
	var b strings.Builder
	b.WriteString("# " + lang.title + "\n\n" + generated + "\n\n")
	intro := see
	if rec := r.known()[see]; rec != nil {
		intro = "[" + see + "](" + link(rec, lang.ja) + ")"
	}
	b.WriteString(fmt.Sprintf(lang.intro, intro) + "\n\n")
	var rows []string
	for _, rec := range r.records {
		if rec.en == nil {
			continue
		}
		fm := fronts[rec]
		status := fm.status
		if by := supersededBy[rec.id]; len(by) > 0 {
			links := make([]string, 0, len(by))
			for _, o := range by {
				links = append(links, "["+o.id+"]("+link(o, lang.ja)+")")
			}
			status = lang.superseded + strings.Join(links, lang.separator)
		}
		title := titleOf(rec.en, rec.id)
		if lang.ja && rec.ja != nil {
			title = titleOf(rec.ja, rec.id)
		}
		rows = append(rows, "| ["+rec.id+"]("+link(rec, lang.ja)+") | "+cell(title)+" | "+cell(status)+" | "+cell(fm.date)+" |")
	}
	if len(rows) == 0 {
		b.WriteString(lang.none + "\n")
	} else {
		b.WriteString(lang.columns + "\n|---|---|---|---|\n" + strings.Join(rows, "\n") + "\n")
	}
	return []byte(b.String())
}

// link returns the path of a record relative to docs/adr/: its translation
// for the Japanese index when there is one.
func link(rec *record, ja bool) string {
	f := rec.en
	if ja && rec.ja != nil {
		f = rec.ja
	}
	return strings.TrimPrefix(f.path, recordsDir+"/")
}

// cell escapes the pipes in a table cell.
func cell(s string) string {
	return strings.ReplaceAll(s, "|", `\|`)
}

// WriteIndex writes docs/adr/README.md and docs/adr/README.ja.md under root,
// and writes one line to w for each file that it changed.
func WriteIndex(root *os.Root, w io.Writer) error {
	r, err := load(root.FS())
	if err != nil {
		return err
	}
	en, ja := r.index()
	if err := root.MkdirAll(filepath.FromSlash(recordsDir), 0o750); err != nil {
		return err
	}
	if err := writeIfChanged(root, indexEN, en, w); err != nil {
		return err
	}
	return writeIfChanged(root, indexJA, ja, w)
}

// writeIfChanged writes data to the file p under root unless the file already
// holds data, and reports a change on w.
func writeIfChanged(root *os.Root, p string, data []byte, w io.Writer) error {
	name := filepath.FromSlash(p)
	old, err := root.ReadFile(name)
	action := "updated"
	switch {
	case errors.Is(err, fs.ErrNotExist):
		action = "created"
	case err != nil:
		return err
	case bytes.Equal(old, data):
		return nil
	}
	if err := root.WriteFile(name, data, 0o644); err != nil {
		return err
	}
	_, err = fmt.Fprintf(w, "%s: %s\n", p, action)
	return err
}
