func TestDescribe(t *testing.T) {
	for _, srv := range eachServer(t) {
		t.Run(srv.Name, func(t *testing.T) {
			db := database(t, srv)
			db.Exec(t, `
			CREATE SCHEMA s;
			CREATE TABLE s.no_key (a integer, b text NOT NULL);
			CREATE TABLE s.keys (
				id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
				code text NOT NULL CONSTRAINT keys_code_unique UNIQUE,
				x integer NOT NULL,
				y integer NOT NULL,
				z integer,
				w text,
				dropped integer,
				doubled integer GENERATED ALWAYS AS (x * 2) STORED,
				counter integer GENERATED BY DEFAULT AS IDENTITY,
				CONSTRAINT keys_xy UNIQUE (y, x),
				CONSTRAINT keys_deferred UNIQUE (z) DEFERRABLE
			);
			ALTER TABLE s.keys DROP COLUMN dropped;
			CREATE UNIQUE INDEX keys_w_index ON s.keys (w) INCLUDE (z);
			CREATE UNIQUE INDEX keys_partial ON s.keys (x) WHERE z > 0;
			CREATE UNIQUE INDEX keys_expression ON s.keys (lower(w));
			CREATE UNIQUE INDEX keys_invalid ON s.keys (z, w);
			UPDATE pg_index SET indisvalid = false WHERE indexrelid = 's.keys_invalid'::regclass;
			CREATE INDEX keys_not_unique ON s.keys (y);
			CREATE TABLE s.composite (b text, a integer, c text, PRIMARY KEY (b, a));
			CREATE SCHEMA "Mixed";
			CREATE TABLE "Mixed"."Case Table" ("ID" integer PRIMARY KEY, "Name" text);
			CREATE TABLE s.parted (country text, zip text, city text, PRIMARY KEY (country, zip)) PARTITION BY LIST (country);
			CREATE TABLE s.parted_jp PARTITION OF s.parted FOR VALUES IN ('jp') PARTITION BY RANGE (zip);
			CREATE TABLE s.parted_jp_east PARTITION OF s.parted_jp FOR VALUES FROM ('0') TO ('5');
			CREATE TABLE s.inherits (extra text) INHERITS (s.no_key);
			CREATE TABLE s.empty ();
			CREATE SCHEMA sales;
			CREATE SCHEMA "Sales";
			CREATE TABLE "Sales".rooms (id integer);
			CREATE TABLE s."écart" (id integer);
			CREATE TABLE s."Écran" (id integer);
			CREATE DOMAIN s.d_default AS integer DEFAULT 7;
			CREATE DOMAIN s.d_inner AS integer DEFAULT 5;
			CREATE DOMAIN s.d_outer AS s.d_inner;
			CREATE DOMAIN s.d_plain AS integer;
			CREATE TABLE s.defaults (
				plain integer NOT NULL,
				with_default integer DEFAULT 1,
				serial_id serial,
				by_domain s.d_default,
				by_outer s.d_outer,
				by_plain s.d_plain,
				always integer GENERATED ALWAYS AS IDENTITY,
				by_default integer GENERATED BY DEFAULT AS IDENTITY,
				generated integer GENERATED ALWAYS AS (plain + 1) STORED
			);
		`)
			s := db.session(t, t.TempDir())
			name := func(schema, table string) declaration.TableName {
				return declaration.TableName{Schema: schema, Name: table}
			}
			want := map[declaration.TableName]plan.TableInfo{
				name("s", "no_key"): {
					Exists:  true,
					Columns: []plan.ColumnInfo{{Name: "a"}, {Name: "b", NotNull: true}},
				},
				name("s", "keys"): {
					Exists: true,
					Columns: []plan.ColumnInfo{
						{Name: "id", NotNull: true, IdentityAlways: true, HasDefault: true, Sequence: true},
						{Name: "code", NotNull: true},
						{Name: "x", NotNull: true},
						{Name: "y", NotNull: true},
						{Name: "z"},
						{Name: "w"},
						{Name: "doubled", Generated: true, HasDefault: true},
						{Name: "counter", NotNull: true, HasDefault: true, Sequence: true},
					},
					PrimaryKey: []string{"id"},
					// Sorted by the name of the index.
					UniqueKeys: [][]string{{"code"}, {"w"}, {"y", "x"}},
				},
				name("s", "composite"): {
					Exists:     true,
					Columns:    []plan.ColumnInfo{{Name: "b", NotNull: true}, {Name: "a", NotNull: true}, {Name: "c"}},
					PrimaryKey: []string{"b", "a"},
				},
				name("Mixed", "Case Table"): {
					Exists:     true,
					Columns:    []plan.ColumnInfo{{Name: "ID", NotNull: true}, {Name: "Name"}},
					PrimaryKey: []string{"ID"},
				},
				// A name that does not exist names the tables, or else the
				// schemas, that differ from it only in white space or case.
				name("mixed", "case table"): {NearNames: []declaration.TableName{name("Mixed", "Case Table")}},
				name("S", "KEYS"):           {NearNames: []declaration.TableName{name("s", "keys")}},
				name(" s ", "nothing"):      {NearSchemas: []string{"s"}},
				name("S", "nothing"):        {NearSchemas: []string{"s"}},
				// A schema that exists as it is named, next to one in another
				// case: the table waits for the schema change, also when the
				// other schema has it.
				name("sales", "new_table"): {},
				name("sales", "rooms"):     {},
				name("Sales", "Rooms"):     {NearNames: []declaration.TableName{name("Sales", "rooms")}},
				// Only ASCII letters are folded, in both directions.
				name("s", "Écart"): {},
				name("s", "écran"): {},
				name("s", "parted"): {
					Exists:     true,
					Columns:    []plan.ColumnInfo{{Name: "country", NotNull: true}, {Name: "zip", NotNull: true}, {Name: "city"}},
					PrimaryKey: []string{"country", "zip"},
					Partitions: []declaration.TableName{name("s", "parted_jp"), name("s", "parted_jp_east")},
				},
				// A partition names the partitioned tables above it, nearest
				// first; a table that inherits from another is no partition.
				name("s", "parted_jp"): {
					Exists:      true,
					Columns:     []plan.ColumnInfo{{Name: "country", NotNull: true}, {Name: "zip", NotNull: true}, {Name: "city"}},
					PrimaryKey:  []string{"country", "zip"},
					PartitionOf: []declaration.TableName{name("s", "parted")},
					Partitions:  []declaration.TableName{name("s", "parted_jp_east")},
				},
				name("s", "parted_jp_east"): {
					Exists:      true,
					Columns:     []plan.ColumnInfo{{Name: "country", NotNull: true}, {Name: "zip", NotNull: true}, {Name: "city"}},
					PrimaryKey:  []string{"country", "zip"},
					PartitionOf: []declaration.TableName{name("s", "parted_jp"), name("s", "parted")},
				},
				name("s", "inherits"): {
					Exists:  true,
					Columns: []plan.ColumnInfo{{Name: "a"}, {Name: "b", NotNull: true}, {Name: "extra"}},
				},
				name("s", "empty"): {Exists: true},
				// A column of a domain over a domain with a default gets that
				// default: CREATE DOMAIN copies the default of its base domain.
				name("s", "defaults"): {
					Exists: true,
					Columns: []plan.ColumnInfo{
						{Name: "plain", NotNull: true},
						{Name: "with_default", HasDefault: true},
						{Name: "serial_id", NotNull: true, HasDefault: true, Sequence: true},
						{Name: "by_domain", HasDefault: true},
						{Name: "by_outer", HasDefault: true},
						{Name: "by_plain"},
						{Name: "always", NotNull: true, IdentityAlways: true, HasDefault: true, Sequence: true},
						{Name: "by_default", NotNull: true, HasDefault: true, Sequence: true},
						{Name: "generated", Generated: true, HasDefault: true},
					},
				},
				name("s", "missing"):   {},
				name("nowhere", "any"): {},
			}
			names := make([]declaration.TableName, 0, len(want)+1)
			for n := range want {
				names = append(names, n)
			}
			// A name twice is described once.
			names = append(names, name("s", "keys"))
			got, err := s.Describe(t.Context(), names)
			if err != nil {
				t.Fatalf("Describe: %v", err)
			}
			if len(got) != len(want) {
				t.Errorf("Describe returned %d tables, want %d", len(got), len(want))
			}
			for n, w := range want {
				if g := got[n]; !reflect.DeepEqual(g, w) {
					t.Errorf("Describe(%s):\ngot  %+v\nwant %+v", n, g, w)
				}
			}
			// A new row that names only plain gets a value in exactly the
			// columns that HasDefault marks.
			db.Exec(t, `INSERT INTO s.defaults (plain) VALUES (1)`)
			row := db.Query(t, `SELECT with_default, serial_id, by_domain, by_outer, by_plain, always, by_default, generated FROM s.defaults`)
			if fmt.Sprint(row) != "[[1 1 7 5 NULL 1 1 2]]" {
				t.Errorf("a new row of s.defaults = %v", row)
			}
		})
	}
}

func TestDescribeRelationsThatAreNotTables(t *testing.T) {
	for _, srv := range eachServer(t) {
		t.Run(srv.Name, func(t *testing.T) {
			db := database(t, srv)
			db.Exec(t, `
			CREATE SCHEMA s;
			CREATE TABLE s.t (id integer PRIMARY KEY);
			CREATE VIEW s.v AS SELECT id FROM s.t;
			CREATE MATERIALIZED VIEW s.m AS SELECT id FROM s.t;
			CREATE SEQUENCE s.seq;
			CREATE TYPE s.pair AS (a integer, b integer);
		`)
			s := db.session(t, t.TempDir())
			for _, tt := range []struct{ name, what string }{
				{"v", "a view"},
				{"m", "a materialized view"},
				{"seq", "a sequence"},
				{"t_pkey", "an index"},
				{"pair", "a composite type"},
			} {
				t.Run(tt.name, func(t *testing.T) {
					_, err := s.Describe(t.Context(), []declaration.TableName{{Schema: "s", Name: "t"}, {Schema: "s", Name: tt.name}})
					if err == nil {
						t.Fatal("Describe succeeded, want an error")
					}
					wantError(t, err, fmt.Sprintf("s.%s is %s, not a table", tt.name, tt.what))
				})
			}
		})
	}
}

// Diff and CountRows also work without an earlier Describe.
func TestDiffWithoutDescribe(t *testing.T) {
	for _, srv := range eachServer(t) {
		t.Run(srv.Name, func(t *testing.T) {
			db := database(t, srv)
			db.Exec(t, `CREATE SCHEMA s; CREATE TABLE s.t (id integer PRIMARY KEY, v text); CREATE VIEW s.v AS SELECT * FROM s.t;`)
			dir := writeFiles(t, map[string]string{"s/t.csv": "id,v\n1,a\n"})
			s := db.session(t, dir)
			checkDiff(t, s, plan.DiffRequest{Table: csvTable("s", "t", "id", "v"), Key: []string{"id"}, Compare: []string{"v"}}, `+ "1" | "a"`)
			err := diffError(t, s, plan.DiffRequest{Table: csvTable("s", "v", "id", "v"), Key: []string{"id"}})
			wantError(t, err, "s.v is a view, not a table")
		})
	}
}

// A unique key is kept only when its index matches rows as a plan does: with
// the collation of each column and the default operator class of its type.
func TestDescribeKeysThatMatchAsAPlanDoes(t *testing.T) {
	for _, srv := range eachServer(t) {
		t.Run(srv.Name, func(t *testing.T) {
			db := database(t, srv)
			db.Exec(t, `
				CREATE SCHEMA s;
				CREATE COLLATION s.ci (provider = icu, locale = 'und-u-ks-level2', deterministic = false);
				CREATE TABLE s.coll (
					id integer PRIMARY KEY,
					code text COLLATE s.ci NOT NULL CONSTRAINT coll_code UNIQUE,
					slug text NOT NULL,
					tag text NOT NULL,
					n integer NOT NULL
				);
				CREATE UNIQUE INDEX coll_code_c ON s.coll (code COLLATE "C");
				CREATE UNIQUE INDEX coll_slug_pattern ON s.coll (slug text_pattern_ops);
				CREATE UNIQUE INDEX coll_tag ON s.coll (tag);
				CREATE UNIQUE INDEX coll_tag_n ON s.coll (tag COLLATE "C", n);
				INSERT INTO s.coll VALUES (1, 'ABC', 'abc', 'x', 1);
			`)
			dir := writeFiles(t, map[string]string{"s/coll.csv": "code,slug\nabc,abc\n"})
			s := db.session(t, dir)
			name := declaration.TableName{Schema: "s", Name: "coll"}
			infos, err := s.Describe(t.Context(), []declaration.TableName{name})
			if err != nil {
				t.Fatal(err)
			}
			if got, want := infos[name].UniqueKeys, [][]string{{"code"}, {"tag"}}; !reflect.DeepEqual(got, want) {
				t.Errorf("UniqueKeys = %v, want %v", got, want)
			}
			// The keys that are set aside are reported with the reason, so
			// that an error can say why such a key does not match rows.
			wantAside := []plan.SetAsideKey{
				{Columns: []string{"code"}, Reason: `its index uses another collation than column "code"`},
				{Columns: []string{"slug"}, Reason: `its index uses an operator class that is not the default for column "slug"`},
				{Columns: []string{"tag", "n"}, Reason: `its index uses another collation than column "tag"`},
			}
			if got := infos[name].SetAsideKeys; !reflect.DeepEqual(got, wantAside) {
				t.Errorf("SetAsideKeys = %+v, want %+v", got, wantAside)
			}
			// The key matches with the collation of the column: abc is ABC.
			checkDiff(t, s, plan.DiffRequest{
				Table: csvTable("s", "coll", "code", "slug"), Key: []string{"code"}, Compare: []string{"slug"}, Updates: true, Deletes: true,
			})
		})
	}
}
