//go:build integration

package main

import (
	"fmt"
	"strings"
	"testing"

	"github.com/ma-chisuke/kortopi/internal/postgres/pgtest"
)

// sequenceSchema holds the tables of issue 29: an identity column and a
// serial column, whose sequences the application took 1 and 2 from.
const sequenceSchema = `CREATE SCHEMA billing;
	CREATE TABLE billing.tax_rates (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL UNIQUE, rate numeric(5,4) NOT NULL);
	CREATE TABLE billing.fees (id serial PRIMARY KEY, name text NOT NULL UNIQUE, amount int NOT NULL);
	INSERT INTO billing.tax_rates (name, rate) VALUES ('standard', 0.1000), ('reduced', 0.0800);
	INSERT INTO billing.fees (name, amount) VALUES ('shipping', 500), ('wrapping', 200);`

// sequenceFiles add a row with the ID 3 to each table of sequenceSchema.
var sequenceFiles = map[string]string{
	"billing/tax_rates.csv": "id,name,rate\n1,standard,0.1000\n2,reduced,0.0800\n3,zero,0.0000\n",
	"billing/fees.csv":      "id,name,amount\n1,shipping,500\n2,wrapping,200\n3,express,900\n",
}

// sequencePlan is the plan of sequenceFiles against sequenceSchema.
var sequencePlan = lines(
	"billing.fees (upsert, key: id)",
	"  + id=3  name=express  amount=900",
	"  1 to insert, 0 to update",
	"  sequence billing.fees_id_seq of column id: next value 3 -> 4",
	"",
	"billing.tax_rates (upsert, key: id)",
	"  + id=3  name=zero  rate=0.0000",
	"  1 to insert, 0 to update",
	"  sequence billing.tax_rates_id_seq of column id: next value 3 -> 4",
	"",
	"Plan: 2 to insert, 0 to update, 0 to delete in 2 tables.",
)

// nextIDs inserts a row into each table of sequenceSchema as the
// application does, with the ID from the sequence, and returns the IDs.
const nextIDs = `INSERT INTO billing.tax_rates (name, rate) VALUES ('special', 0.0500) RETURNING 'tax_rates ' || id;
	INSERT INTO billing.fees (name, amount) VALUES ('gift', 300) RETURNING 'fees ' || id;`

// TestSequencesCommand runs issue 29 as the binary does, against each
// version (ADR-0045): the plan shows where each sequence would move, the
// apply moves it, and the next insert of the application gets the ID 4. The
// plan as SQL, run through a plain connection, does the same, and moves no
// sequence back when it runs after the application took more values. It
// sets the environment, so it does not run in parallel with other tests.
func TestSequencesCommand(t *testing.T) {
	for _, srv := range pgtest.Servers() {
		t.Run(srv.Name, func(t *testing.T) {
			dir := writeFiles(t, sequenceFiles)
			db := srv.Database(t)
			db.Exec(t, sequenceSchema)
			e := connect(t, db)

			code, stdout, stderr := e.command(t, "plan", "--dir", dir)
			checkRun(t, code, stdout, stderr, exitOK, sequencePlan)

			code, stdout, stderr = e.command(t, "apply", "--dir", dir)
			checkRun(t, code, stdout, stderr, exitOK, sequencePlan+lines("",
				"Applied: 2 inserted, 0 updated, 0 deleted.",
				"Sequence billing.fees_id_seq of billing.fees (id): next value 3 -> 4.",
				"Sequence billing.tax_rates_id_seq of billing.tax_rates (id): next value 3 -> 4."))
			if got := db.Query(t, nextIDs); fmt.Sprint(got) != "[[tax_rates 4] [fees 4]]" {
				t.Errorf("the next insert of the application got %v, want the ID 4 in each table", got)
			}
			code, stdout, stderr = e.command(t, "plan", "--dir", dir, "--exit-code")
			checkRun(t, code, stdout, stderr, exitOK, "No changes. The database matches the declaration.\n")

			for _, later := range []bool{false, true} {
				db := srv.Database(t)
				db.Exec(t, sequenceSchema)
				e := connect(t, db)
				code, stdout, stderr := e.command(t, "plan", "--dir", dir, "--format", "sql")
				if code != exitOK || stderr != "" || !strings.Contains(stdout, "-- billing.fees: sequence billing.fees_id_seq of column id: next value 3 -> 4\n") {
					t.Fatalf("kortopi plan --format sql = %d, stdout\n%s\nstderr\n%s\nwant the move of the sequences", code, stdout, stderr)
				}
				want := "[[tax_rates 4] [fees 4]]"
				if later {
					// The application takes ten values from each sequence
					// after the plan and before the script.
					db.Exec(t, `SELECT nextval('billing.fees_id_seq'), nextval('billing.tax_rates_id_seq') FROM generate_series(1, 10)`)
					want = "[[tax_rates 13] [fees 13]]"
				}
				db.Exec(t, "BEGIN;\n"+stdout+"COMMIT;\n")
				if got := db.Query(t, nextIDs); fmt.Sprint(got) != want {
					t.Errorf("after the script, run later: %t, the next insert of the application got %v, want %s", later, got, want)
				}
			}
		})
	}
}
